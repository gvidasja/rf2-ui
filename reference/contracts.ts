const UNSAFE = /\/(start|stop|join|reset[a-z]*|settarget|play|getAuthSessionTicket|toRaceMenu|quit|exit|delete|install|uninstall|kick|add)(\/|$)/i;

async function fetchSamples(endpoints: Endpoint[]) {
  const result = new Map<string, { file: string; warnings: string[]; json: unknown }>();
  if (!(await gameUp())) {
    // Game not running: reuse samples saved by an earlier run so API.md keeps them.
    const fs = require("fs");
    for (const e of endpoints) {
      const file = e.path.replace(/^\//, "").replace(/[^a-z0-9]+/gi, "_") + ".json";
      const p = join(genDir, "samples", file);
      if (e.httpMethod === "GET" && fs.existsSync(p)) result.set(`${e.httpMethod} ${e.path}`, { file, warnings: [], json: JSON.parse(fs.readFileSync(p, "utf8")) });
    }
    return result;
  }
  for (const e of endpoints) {
    if (CRASHES[`${e.httpMethod} ${e.path}`] || e.httpMethod !== "GET" || e.path.includes("{") || UNSAFE.test(e.path) || /image|thumbnail|texture|download/i.test(e.path)) continue;
    try {
      const res = await fetch(GAME + e.path, { signal: AbortSignal.timeout(5000) });
      if (!(res.headers.get("content-type") ?? "").includes("json")) continue;
      const json = await res.json();
      const file = e.path.replace(/^\//, "").replace(/[^a-z0-9]+/gi, "_") + ".json";
      write(join(genDir, "samples", file), JSON.stringify(json, null, 2));
      result.set(`${e.httpMethod} ${e.path}`, { file, warnings: [], json });
    } catch {}
  }
  return result;
}

// ---------- recorded stock UI traffic (legacy/recorder.ts -> .recordings/) ----------
function recordings(endpoints: Endpoint[]) {
  const fs = require("fs");
  const out = new Map<string, { url: string; status: number; request?: unknown; response?: unknown }[]>();
  const dir = join(here, "..", ".recordings");
  if (!fs.existsSync(dir)) return out;
  const res = endpoints.map((e) => ({ e, re: new RegExp("^" + e.path.replace(/\{[^}]+\}/g, "[^/]+") + "/?$") }));
  for (const f of fs.readdirSync(dir).filter((f: string) => f.endsWith(".json"))) {
    const r = JSON.parse(fs.readFileSync(join(dir, f), "utf8"));
    const path = new URL(r.url, "http://x").pathname;
    if (/AuthSessionTicket/i.test(path)) continue; // credentials
    const hasBody = r.request !== undefined && r.request !== null && r.request !== "";
    const candidates = res.filter((x) => x.re.test(path));
    const hit = candidates.find((x) => (hasBody ? x.e.httpMethod !== "GET" : x.e.httpMethod === "GET")) ?? candidates[0];
    if (!hit) continue;
    const key = `${hit.e.httpMethod} ${hit.e.path}`;
    out.set(key, [...(out.get(key) ?? []), { url: r.url, status: r.status, request: hasBody ? r.request : undefined, response: r.response }]);
  }
  return out;
}

function clip(v: unknown) {
  const s = typeof v === "string" ? v : JSON.stringify(v);
  return (s.length > 120 ? s.slice(0, 120) + "…" : s).replace(/`/g, "'").replace(/\|/g, "\\|");
}

