// REST contracts and native API, derived from the game's Java classes (Swagger only shows private fields).
//
// Outputs: API.md, rf2-api.ts (TypeScript types + endpoint map), NATIVE.md,
//          generated/samples/*.json (live GET samples, gitignored) used to sanity-check the types.
import { $ } from "bun";
import { join, relative } from "path";
import { classesDir, dmDescriptors, ensureClasses, GAME, gameUp, genDir, here, write } from "./lib";
import { type ClassInfo, type JType, jacksonName, loadClasses, parseType } from "./java";

/** Endpoints known to crash rFactor2.exe (native access violation) when called in the wrong context. */
export const CRASHES: Record<string, string> = {
  "GET /rest/replay/numberofonboardcameras": "crashes the game (native access violation in Replays.getOnboardCameras) when no replay is playing",
};

type Param = { name: string; kind: "path" | "query" | "form" | "header" | "body" | "context"; type: string };
type Endpoint = {
  group: string;
  httpMethod: string;
  path: string;
  javaClass: string;
  javaMethod: string;
  params: Param[];
  ret: string;
  produces?: string;
  consumes?: string;
  description?: string;
};

export async function contracts() {
  await ensureClasses();
  const classes = await loadClasses();
  const dm = await dmDescriptors();
  const endpoints = await collectEndpoints(dm);

  // ---------- TypeScript types ----------
  const ts = new TsTypes(classes);
  const endpointTypes = endpoints.map((e) => ({
    e,
    body: e.params.find((p) => p.kind === "body"),
    bodyTs: (() => {
      const b = e.params.find((p) => p.kind === "body");
      return b ? ts.of(parseType(b.type)) : undefined;
    })(),
    retTs: ts.of(parseType(e.ret), true),
  }));

  // ---------- call graph to natives ----------
  const graph = new CallGraph(classes);
  const natives = graph.natives();
  const reach = new Map<string, Set<string>>(); // endpoint key -> natives
  const serviceOf = new Map<string, Set<string>>(); // native -> service interface methods reaching it
  for (const { e } of endpointTypes) {
    const key = `${e.httpMethod} ${e.path}`;
    reach.set(key, graph.reachableNatives(`${e.javaClass}#${e.javaMethod}`));
  }
  for (const svc of [...classes.values()].filter((c) => c.kind === "interface" && /^net\.rfactor2\.(?!jni|ui|rest|app)/.test(c.name) && /Service$/.test(c.name))) {
    for (const m of svc.methods) {
      for (const n of graph.reachableNatives(`${svc.name}#${m.name}`)) {
        if (!serviceOf.has(n)) serviceOf.set(n, new Set());
        serviceOf.get(n)!.add(`${short(svc.name)}.${m.name}`);
      }
    }
  }
  const nativeToEndpoints = new Map<string, string[]>();
  for (const [ep, ns] of reach) for (const n of ns) nativeToEndpoints.set(n, [...(nativeToEndpoints.get(n) ?? []), ep]);

  // ---------- live samples ----------
  const samples = await fetchSamples(endpoints);
  const recorded = recordings(endpoints);
  for (const e of endpoints) {
    const s = samples.get(`${e.httpMethod} ${e.path}`);
    if (s) s.warnings = ts.check(parseType(e.ret), s.json);
  }

  // ---------- rf2-api.ts ----------
  const tsOut: string[] = [];
  tsOut.push("// Generated by `bun reference/dump.ts` from the game's Java classes (Jackson rules: public getters + public fields;");
  tsOut.push("// the apps' ObjectMapper uses NON_NULL, so non-primitive properties may be missing). Do not edit.");
  tsOut.push("");
  // resolve param types first so their declarations are emitted too
  const endpointLines = endpointTypes.map(({ e, bodyTs, retTs }) => {
    const ps = e.params.filter((p) => p.kind === "path" || p.kind === "query");
    const params = ps.length ? `{ ${ps.map((p) => `${JSON.stringify(p.name)}${p.kind === "query" ? "?" : ""}: ${ts.of(parseType(p.type))}`).join("; ")} }` : "{}";
    return `  ${JSON.stringify(`${e.httpMethod} ${e.path}`)}: { params: ${params}; body: ${bodyTs ?? "never"}; response: ${retTs} };`;
  });
  tsOut.push(ts.declarations());
  tsOut.push("");
  tsOut.push("/** Every REST endpoint: `params` = path/query params, `body` = JSON request body, `response` = JSON response. */");
  tsOut.push("export interface Endpoints {");
  tsOut.push(...endpointLines);
  tsOut.push("}");
  write(join(here, "rf2-api.ts"), tsOut.join("\n") + "\n");

  // ---------- API.md ----------
  const md: string[] = [];
  const groups = [...new Set(endpoints.map((e) => e.group))].sort();
  md.push("# rFactor 2 REST API — contracts");
  md.push("");
  md.push("Generated by `bun reference/dump.ts` from the game's Java classes. Types are TypeScript, as defined in");
  md.push("[`rf2-api.ts`](rf2-api.ts) (`Endpoints` maps `\"METHOD /path\"` → params/body/response). Natives: see [NATIVE.md](NATIVE.md).");
  md.push("");
  md.push("- JSON follows Jackson's defaults: public getters (`getFoo` → `foo`, `isFoo` → `foo`) and public fields; nulls are omitted.");
  md.push("- Enums serialize as their constant names; `Map<Enum, V>` becomes an object keyed by constant name.");
  md.push("- A body param of type `string` is sent raw (not JSON); most `POST`s without `Consumes` take `text/plain`.");
  md.push("- Every call into the game runs on the game thread via a command queue (`net.rfactor2.jni.Queue`).");
  md.push(`- ${endpoints.length} endpoints in ${groups.length} groups. Live samples: ${samples.size} (\`generated/samples/\`, gitignored).`);
  md.push("");
  md.push(groups.map((g) => `[${g}](#${g.replace(/[^a-z0-9]+/gi, "").toLowerCase()})`).join(" · "));
  md.push("");
  for (const g of groups) {
    md.push(`## ${g}`);
    md.push("");
    for (const { e, bodyTs, retTs } of endpointTypes.filter((x) => x.e.group === g)) {
      const key = `${e.httpMethod} ${e.path}`;
      md.push(`### \`${key}\``);
      md.push("");
      if (CRASHES[key]) md.push(`> **⚠ ${CRASHES[key]}.**`), md.push("");
      if (e.description) md.push(e.description.replace(/\s+/g, " ")), md.push("");
      const lines: string[] = [];
      for (const p of e.params.filter((p) => p.kind !== "body" && p.kind !== "context")) lines.push(`- ${p.kind} \`${p.name}\`: \`${ts.of(parseType(p.type))}\``);
      if (bodyTs) lines.push(`- body${e.consumes ? ` (${e.consumes})` : ""}: \`${bodyTs}\``);
      lines.push(`- response${e.produces ? ` (${e.produces})` : ""}: \`${retTs}\``);
      lines.push(`- Java: \`${short(e.javaClass)}.${e.javaMethod}\``);
      const ns = [...(reach.get(key) ?? [])];
      if (ns.length) lines.push(`- natives: ${ns.slice(0, 8).map((n) => `\`${n}\``).join(", ")}${ns.length > 8 ? ` +${ns.length - 8}` : ""}`);
      for (const r of recorded.get(key) ?? []) lines.push(`- recorded from the stock UI: \`${r.url}\`${r.request !== undefined ? ` request \`${clip(r.request)}\`` : ""} → ${r.status}`); // responses left out: they hold personal data (profile, paths); see samples
      const sample = samples.get(key);
      if (sample) {
        lines.push(`- sample: \`generated/samples/${sample.file}\``);
        for (const w of sample.warnings) lines.push(`- ⚠ type check: ${w}`);
      }
      md.push(...lines, "");
    }
  }
  md.push("## Types");
  md.push("");
  md.push("See [`rf2-api.ts`](rf2-api.ts).");
  write(join(here, "API.md"), md.join("\n"));

  // ---------- NATIVE.md ----------
  const nm: string[] = [];
  nm.push("# Native API (`rFactor2.exe` via JNI)");
  nm.push("");
  nm.push("Generated by `bun reference/dump.ts`. Every `native` method in `Bin/rFactor2.jar` (`net.rfactor2.jni.*`).");
  nm.push("Java services (`net.rfactor2.<area>.<X>Service`, OSGi) wrap them in commands queued onto the game thread;");
  nm.push("a bundle can depend on those services (see `bundle/` in this repo). The UI reaches them through REST endpoints");
  nm.push("and through the websocket channel `/ui` (topics pushed to the page); a few are only used by other bundles.");
  nm.push("Natives reached from nowhere are capabilities nothing uses today — candidates for new endpoints.");
  nm.push("");

  // Non-REST entry points: websocket topic pollers/providers, plugins and service implementations in other bundles.
  const otherCallers = new Map<string, Set<string>>(); // native -> labels
  for (const c of classes.values()) {
    const ws = /\.websocket\./.test(c.name);
    const plugin = /^net\.rfactor2\.(plugin|[a-z]+\.impl)\./.test(c.name) || /^net\.rfactor2\.(automation|overlay)\./.test(c.name);
    if (!ws && !plugin) continue;
    const label = ws ? `websocket: ${short(c.name).replace(/\$.*$/, "")}` : `bundle: ${short(c.name).replace(/\$.*$/, "")}`;
    for (const m of c.methods) {
      for (const n of graph.reachableNatives(`${c.name}#${m.name}`)) {
        if (!otherCallers.has(n)) otherCallers.set(n, new Set());
        otherCallers.get(n)!.add(label);
      }
    }
  }
  const byPkg = new Map<string, string[]>();
  for (const n of natives) {
    const pkg = n.split("#")[0].split(".").slice(3, -1).join(".") || "jni";
    byPkg.set(pkg, [...(byPkg.get(pkg) ?? []), n]);
  }
  const restOnly = natives.filter((n) => nativeToEndpoints.has(n));
  const otherOnly = natives.filter((n) => !nativeToEndpoints.has(n) && otherCallers.has(n));
  const unexposed = natives.filter((n) => !nativeToEndpoints.has(n) && !otherCallers.has(n));
  nm.push(`${natives.length} natives: ${restOnly.length} reachable from REST, ${otherOnly.length} only through websocket topics or other bundles, **${unexposed.length} unused**.`);
  nm.push("");
  if (unexposed.length) {
    nm.push("## Unused");
    nm.push("");
    for (const n of unexposed.sort()) nm.push(`- \`${short(n.split("#")[0])}.${n.split("#")[1]}\`${serviceOf.has(n) ? ` (via ${[...serviceOf.get(n)!].join(", ")})` : ""}`);
    nm.push("");
  }
  for (const [pkg, list] of [...byPkg].sort()) {
    nm.push(`## ${pkg}`);
    nm.push("");
    nm.push("| native | via service | reached from |");
    nm.push("|---|---|---|");
    for (const n of list.sort()) {
      const [cls, m] = n.split("#");
      const info = classes.get(cls)!.methods.find((x) => x.name === m && x.isNative)!;
      const sig = `${short(cls)}.${m}(${info.params.map((p) => short(p)).join(", ")}): ${short(info.ret)}`;
      const svc = [...(serviceOf.get(n) ?? [])].slice(0, 4).join(", ");
      const eps = (nativeToEndpoints.get(n) ?? []).map((x) => `\`${x}\``);
      const other = [...(otherCallers.get(n) ?? [])];
      const from = [...eps.slice(0, 4), ...(eps.length > 4 ? [`+${eps.length - 4} endpoints`] : []), ...other.slice(0, 3)];
      nm.push(`| \`${sig}\` | ${svc} | ${from.length ? from.join("<br>") : "**unused**"} |`);
    }
    nm.push("");
  }
  write(join(here, "NATIVE.md"), nm.join("\n"));

  const warnCount = [...samples.values()].reduce((n, s) => n + s.warnings.length, 0);
  console.log(`contracts: ${endpoints.length} endpoints, ${ts.count()} types, ${natives.length} natives (${unexposed.length} unexposed), ${samples.size} samples, ${warnCount} type warnings`);
}

function short(name: string) {
  return name.replace(/^java\.(lang|util)\./, "").replace(/^([a-z0-9]+\.)+/, "");
}

// ---------- REST endpoints from JAX-RS annotations ----------
async function collectEndpoints(dm: Record<string, any[]>): Promise<Endpoint[]> {
  const apps = new Map<string, string>(); // jaxrs name -> base
  const resources: { cls: string; app: string }[] = [];
  for (const lines of Object.values(dm)) {
    for (const c of lines.filter((l) => l.type === "Component")) {
      const p = c.properties ?? {};
      if (p["osgi.jaxrs.application.base"]) apps.set(p["osgi.jaxrs.name"], p["osgi.jaxrs.application.base"]);
      if (p["osgi.jaxrs.resource"]) resources.push({ cls: c.impl, app: p["osgi.jaxrs.application.select"] });
    }
  }
  const endpoints: Endpoint[] = [];
  for (const r of resources) {
    const base = apps.get(r.app);
    if (base === undefined) continue;
    const file = r.cls.replaceAll(".", "/") + ".class";
    const text = await $`javap -v -p ${file}`.cwd(classesDir).quiet().text();
    const classPath = text.split(/\n(?=RuntimeVisibleAnnotations:|SourceFile:)/).slice(1).join("\n").match(/javax\.ws\.rs\.Path\(\s*value="([^"]*)"/)?.[1] ?? "";
    // split into member blocks (2-space indented declarations)
    const blocks = text.split(/\r?\n(?= {2}\S[^\n]*;\r?$)/m);
    for (const b of blocks) {
      const header = b.split(/\r?\n/)[0].trim();
      const http = b.match(/javax\.ws\.rs\.(GET|POST|PUT|DELETE|HEAD|OPTIONS|PATCH)\b/)?.[1];
      if (!http || !header.includes("(")) continue;
      const [annos, paramAnnos = ""] = b.split("RuntimeVisibleParameterAnnotations:");
      const methodPath = annos.match(/javax\.ws\.rs\.Path\(\s*value="([^"]*)"/)?.[1] ?? "";
      const parsed = parseHeader(header);
      const perParam = paramAnnos.split(/parameter \d+:/).slice(1);
      const params: Param[] = parsed.params.map((type, i) => {
        const a = perParam[i] ?? "";
        const m = a.match(/javax\.ws\.rs\.(PathParam|QueryParam|FormParam|HeaderParam|CookieParam|MatrixParam)\(\s*value="([^"]*)"/);
        if (m) return { name: m[2], kind: ({ PathParam: "path", QueryParam: "query", FormParam: "form" } as any)[m[1]] ?? "header", type };
        if (/javax\.ws\.rs\.core\.Context/.test(a)) return { name: `context${i}`, kind: "context", type };
        return { name: "body", kind: "body", type };
      });
      const list = (k: string) => annos.match(new RegExp(`javax\\.ws\\.rs\\.${k}\\(\\s*value=\\[([^\\]]*)\\]`))?.[1]?.replace(/"/g, "");
      const description = [annos.match(/rest\.doc\.Description\(\s*value="([^"]*)"/)?.[1], annos.match(/rest\.doc\.Notes\(\s*value="([^"]*)"/)?.[1]].filter(Boolean).join(" — ") || undefined;
      const path = ("/" + [base, classPath, methodPath].map((s) => s.replace(/^\/|\/$/g, "")).filter(Boolean).join("/")).replace(/\/+/g, "/");
      endpoints.push({
        group: "/" + base.replace(/^\//, ""),
        httpMethod: http,
        path,
        javaClass: r.cls,
        javaMethod: parsed.name,
        params,
        ret: parsed.ret,
        produces: list("Produces"),
        consumes: list("Consumes"),
        description,
      });
    }
  }
  return endpoints.sort((a, b) => a.path.localeCompare(b.path) || a.httpMethod.localeCompare(b.httpMethod));
}

function parseHeader(h: string) {
  const decl = h.replace(/;$/, "").replace(/ throws .*$/, "").replace(/^((public|private|protected|static|final|abstract|synchronized|native) )+/, "").replace(/^<[^()]*?>\s+/, "");
  const paren = decl.indexOf("(");
  const before = decl.slice(0, paren);
  let depth = 0, sp = -1;
  for (let i = before.length - 1; i >= 0; i--) {
    if (before[i] === ">") depth++;
    else if (before[i] === "<") depth--;
    else if (before[i] === " " && depth === 0) {
      sp = i;
      break;
    }
  }
  const params = decl.slice(paren + 1, decl.lastIndexOf(")"));
  const out: string[] = [];
  depth = 0;
  let start = 0;
  for (let i = 0; i < params.length; i++) {
    if (params[i] === "<") depth++;
    else if (params[i] === ">") depth--;
    else if (params[i] === "," && depth === 0) out.push(params.slice(start, i).trim()), (start = i + 1);
  }
  if (params.slice(start).trim()) out.push(params.slice(start).trim());
  return { name: before.slice(sp + 1), ret: before.slice(0, sp), params: out };
}

// ---------- Java -> TypeScript ----------
class TsTypes {
  private decls = new Map<string, string>(); // ts name -> declaration
  private names = new Map<string, string>(); // java class -> ts name
  private props = new Map<string, Map<string, string>>(); // java class -> json props
  constructor(private classes: Map<string, ClassInfo>) {}

  count() {
    return this.decls.size;
  }

  /** Compare a live JSON value with the Java type: unknown keys and missing required properties. */
  check(t: JType, value: unknown, path = "$", out: string[] = []): string[] {
    if (out.length > 5 || value === null || value === undefined) return out;
    if (t.array > 0 || /^java\.util\.(List|Set|Collection)$/.test(t.name)) {
      const inner = t.array > 0 ? { ...t, array: t.array - 1 } : t.args[0];
      if (Array.isArray(value) && value.length && inner) this.check(inner, value[0], `${path}[0]`, out);
      return out;
    }
    if (/^java\.util\.(Map|HashMap|TreeMap|LinkedHashMap|EnumMap)$/.test(t.name)) {
      const first = value && typeof value === "object" ? Object.entries(value)[0] : undefined;
      if (first && t.args[1]) this.check(t.args[1], first[1], `${path}.${first[0]}`, out);
      return out;
    }
    const c = this.classes.get(t.name);
    if (!c || c.kind !== "class" || typeof value !== "object" || Array.isArray(value)) return out;
    const props = this.jsonProps(c);
    if (this.anyGetterOwner(c)) return out;
    for (const k of Object.keys(value as object)) if (!props.has(k)) out.push(`${path}: unexpected key \`${k}\``);
    for (const [k, p] of props) if (!p.optional && !(k in (value as object))) out.push(`${path}: missing \`${k}\``);
    for (const [k, v] of Object.entries(value as object)) {
      const getter = c.methods.find((m) => m.isPublic && !m.params.length && /^(get|is)/.test(m.name) && jacksonName(m.name.replace(/^(get|is)/, "")) === k);
      if (getter) this.check(parseType(getter.ret), v, `${path}.${k}`, out);
    }
    return out;
  }

  declarations() {
    return [...this.decls.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([, d]) => d).join("\n\n");
  }

  of(t: JType, top = false): string {
    let base = this.base(t, top);
    for (let i = 0; i < t.array; i++) base = t.name === "byte" ? "string /* base64 */" : `${wrap(base)}[]`;
    return base;
  }

  private base(t: JType, top: boolean): string {
    const n = t.name;
    if (["int", "long", "short", "byte", "float", "double"].includes(n)) return "number";
    if (/^java\.lang\.(Integer|Long|Short|Byte|Float|Double|Number)$/.test(n) || n === "java.math.BigDecimal") return "number";
    if (n === "boolean" || n === "java.lang.Boolean") return "boolean";
    if (n === "char" || n === "java.lang.String" || n === "java.lang.Character" || n === "java.util.UUID") return "string";
    if (n === "void" || n === "java.lang.Void") return "void";
    if (n === "java.lang.Object" || n === "?" || /^[A-Z]$/.test(n)) return "unknown";
    if (/^java\.time\.|^java\.util\.Date$/.test(n)) return "string /* ISO date */";
    if (/^java\.util\.(List|Set|Collection|ArrayList|HashSet|LinkedList|SortedSet|TreeSet|Queue)$/.test(n)) return `${wrap(this.of(t.args[0] ?? { name: "?", args: [], array: 0 }))}[]`;
    if (/^java\.util\.(Map|HashMap|TreeMap|LinkedHashMap|SortedMap|EnumMap|concurrent\.ConcurrentHashMap)$/.test(n)) {
      const k = t.args[0], v = this.of(t.args[1] ?? { name: "?", args: [], array: 0 });
      const kc = k && this.classes.get(k.name);
      return kc?.kind === "enum" ? `Partial<Record<${this.of(k)}, ${v}>>` : `Record<string, ${v}>`;
    }
    if (n === "java.util.Optional") return `${this.of(t.args[0])} | null`;
    if (/^javax\.ws\.rs\.core\.(Response|StreamingOutput)$|^java\.io\.(InputStream|File)$/.test(n)) return top ? "Blob /* raw response */" : "unknown";
    if (/^com\.fasterxml\.jackson\.databind\.(JsonNode|node\.)/.test(n)) return "unknown";
    const c = this.classes.get(n);
    if (!c) return `unknown /* ${n} */`;
    return this.declare(c);
  }

  private declare(c: ClassInfo): string {
    if (this.names.has(c.name)) return this.names.get(c.name)!;
    const tsName = this.uniqueName(c.name);
    this.names.set(c.name, tsName);
    if (c.kind === "enum") {
      this.decls.set(tsName, `/** ${c.name} */\nexport type ${tsName} = ${c.enumConstants.map((x) => JSON.stringify(x)).join(" | ") || "string"};`);
      return tsName;
    }
    const props = this.jsonProps(c);
    const lines = [...props].sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => `  ${/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k)}${v.optional ? "?" : ""}: ${v.ts};`);
    const anyGetter = this.anyGetter(c);
    // @JsonAnyGetter: the map's entries are flattened into the object next to the fixed properties
    this.decls.set(
      tsName,
      anyGetter
        ? `/** ${c.name} (+ @JsonAnyGetter entries) */\nexport type ${tsName} = {\n${lines.join("\n")}\n} & { [key: string]: ${anyGetter} };`
        : `/** ${c.name} */\nexport interface ${tsName} {\n${lines.join("\n")}\n}`,
    );
    return tsName;
  }

  private jsonProps(c: ClassInfo): Map<string, { ts: string; optional: boolean }> {
    const result = new Map<string, { ts: string; optional: boolean }>();
    const chain: ClassInfo[] = [];
    for (let k: ClassInfo | undefined = c; k && !k.name.startsWith("java."); k = k.superName ? this.classes.get(k.superName) : undefined) chain.unshift(k);
    const primitive = (t: string) => /^(int|long|short|byte|float|double|boolean|char)$/.test(t);
    for (const k of chain) {
      for (const f of k.fields) if (f.isPublic && !f.isStatic) result.set(f.name, { ts: this.of(parseType(f.type)), optional: !primitive(f.type) });
      for (const m of k.methods) {
        if (!m.isPublic || m.isStatic || m.params.length || m.ret === "void" || m.name === "getClass") continue;
        const g = m.name.match(/^get(.+)$/) ?? (m.ret === "boolean" ? m.name.match(/^is(.+)$/) : null);
        if (!g || m.name === this.anyGetterName(k)) continue;
        result.set(jacksonName(g[1]), { ts: this.of(parseType(m.ret)), optional: !primitive(m.ret) });
      }
    }
    return result;
  }

  private anyGetterName(c: ClassInfo) {
    try {
      const bytes = require("fs").readFileSync(join(classesDir, c.name.replaceAll(".", "/") + ".class"));
      if (!bytes.includes("JsonAnyGetter")) return undefined;
    } catch {
      return undefined;
    }
    // the only use in the game: garage Settings.getSettings()
    return c.methods.find((m) => m.isPublic && !m.params.length && /^java\.util\.Map/.test(m.ret))?.name;
  }

  /** Class (self or superclass) declaring @JsonAnyGetter. */
  private anyGetterOwner(c: ClassInfo): ClassInfo | undefined {
    for (let k: ClassInfo | undefined = c; k && !k.name.startsWith("java."); k = k.superName ? this.classes.get(k.superName) : undefined) if (this.anyGetterName(k)) return k;
  }

  private anyGetter(c: ClassInfo) {
    const owner = this.anyGetterOwner(c);
    const name = owner && this.anyGetterName(owner);
    const m = name && owner!.methods.find((x) => x.name === name);
    return m ? this.of(parseType(m.ret).args[1] ?? { name: "?", args: [], array: 0 }) : undefined;
  }

  private uniqueName(java: string) {
    const parts = java.split(".");
    const simple = parts[parts.length - 1].replace(/\$/g, "");
    const taken = new Set(this.names.values());
    if (!taken.has(simple)) return simple;
    const pkg = parts[parts.length - 2];
    return pkg[0].toUpperCase() + pkg.slice(1) + simple;
  }
}

function wrap(t: string) {
  return /[|&\s]/.test(t) && !/^Partial<|^Record</.test(t) ? `(${t})` : t;
}

// ---------- call graph ----------
class CallGraph {
  private implementors = new Map<string, string[]>();
  constructor(private classes: Map<string, ClassInfo>) {
    for (const c of classes.values()) for (const i of c.interfaces) this.implementors.set(i, [...(this.implementors.get(i) ?? []), c.name]);
  }
  natives() {
    const out: string[] = [];
    for (const c of this.classes.values()) for (const m of c.methods) if (m.isNative) out.push(`${c.name}#${m.name}`);
    return [...new Set(out)];
  }
  /**
   * Natives reachable from "class#method". Interfaces resolve to implementors; `new X` follows every method of X
   * (commands' execute(), anonymous classes' run()/call()); invokedynamic follows the class's lambda$ methods.
   */
  reachableNatives(start: string, maxDepth = 12) {
    const ours = (n: string) => /^net\.(rfactor2|gvidasja)\./.test(n);
    const found = new Set<string>();
    const seen = new Set<string>();
    const queue: [string, number][] = [[start, 0]];
    while (queue.length) {
      const [key, d] = queue.shift()!;
      if (seen.has(key) || d > maxDepth) continue;
      seen.add(key);
      const [cls, name] = key.split("#");
      const c = this.classes.get(cls);
      if (!c) continue;
      const targets = c.kind === "interface" ? (this.implementors.get(cls) ?? []).map((i) => `${i}#${name}`) : [];
      for (const m of c.methods.filter((m) => m.name === name)) {
        if (m.isNative) found.add(key);
        for (const call of m.calls) if (ours(call.owner)) targets.push(`${call.owner}#${call.name}`);
        for (const n of m.news) {
          if (!ours(n)) continue;
          const nc = this.classes.get(n);
          for (const x of nc?.methods ?? [{ name: "<init>" }, { name: "execute" }]) targets.push(`${n}#${x.name}`);
        }
        if (m.indy) for (const x of c.methods) if (x.name.startsWith("lambda$")) targets.push(`${cls}#${x.name}`);
      }
      // inherited methods
      if (!c.methods.some((m) => m.name === name) && c.superName?.startsWith("net.rfactor2.")) targets.push(`${c.superName}#${name}`);
      for (const t of targets) queue.push([t, d + 1]);
    }
    return found;
  }
}

