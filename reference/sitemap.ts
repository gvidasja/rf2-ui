// Builds SITEMAP.md: every stock UI screen (ui-router state) per top-level page, with full URL,
// controller, template, the custom components the template uses and a screenshot if one exists.
import { existsSync, readdirSync, readFileSync } from "fs";
import { join, relative } from "path";
import type { Route } from "./extract";
import { genDir, here, readJson, stockDir, walk, write } from "./lib";

// Which page (CEF document) hosts which app's states.
const PAGES: Record<string, { page: string; when: string }> = {
  start: { page: "/start/index.html", when: "Main menu and everything reachable from it (navigationState NAV_MAIN_MENU)." },
  framework: { page: "(shared)", when: "Settings screens, mounted under start.menu and event-settings." },
  event: { page: "/event/index.html", when: "In a session: monitor, live timing, garage/setup, photo mode (NAV_EVENT*, NAV_GARAGE)." },
  loading: { page: "/loading/index.html", when: "While a track/session loads (loadingStatus.loading)." },
  tuning: { page: "/tuning/index.html", when: "Showroom / skin tuning (NAV_TUNING)." },
  materialeditor: { page: "/materialeditor/index.html", when: "Developer material editor." },
};

export function sitemap() {
  const routes = readJson<Route[]>(join(genDir, "routes.json"));
  const byName = new Map(routes.map((r) => [r.name, r]));

  // template path (as referenced, e.g. "start/main-menu/main-menu.html") -> file on disk
  const htmlFiles = new Map<string, string>();
  for (const f of walk(stockDir)) {
    if (!f.endsWith(".html") || f.includes(`${"modules"}`)) continue;
    const rel = relative(stockDir, f).replaceAll("\\", "/");
    htmlFiles.set(rel.split("/").slice(1).join("/"), rel); // drop bundle folder
  }
  // component tag -> template (by file name convention: <tag>.component.html / <tag>.directive.html / <tag>.html)
  const componentTemplates = new Map<string, string>();
  for (const [ref, rel] of htmlFiles) {
    const base = ref.split("/").pop()!.replace(/\.(component|directive)?\.?html$/, "").replace(/\.$/, "");
    if (base.includes("-") && !componentTemplates.has(base)) componentTemplates.set(base, rel);
  }

  const shotDir = join(here, "screenshots");
  const list = (d: string) => (existsSync(d) ? readdirSync(d).filter((f) => f.endsWith(".png")).sort() : []);
  const tabShots = list(shotDir).filter((f) => f.includes("~"));
  const newUiShots = list(join(shotDir, "new-ui"));
  const shotIndex: Record<string, { ok: boolean; error?: string }> = existsSync(join(shotDir, "index.json")) ? readJson(join(shotDir, "index.json")) : {};

  const parentOf = (r: Route) => r.parent ?? (r.name.includes(".") ? r.name.slice(0, r.name.lastIndexOf(".")) : undefined);
  const fullUrl = (r: Route): string => {
    const own = r.url ?? "";
    if (own.startsWith("^")) return own.slice(1);
    const p = parentOf(r);
    const parent = p && byName.get(p);
    return (parent ? fullUrl(parent) : "") + own;
  };
  const depth = (r: Route): number => {
    const p = parentOf(r);
    return p && byName.has(p) ? depth(byName.get(p)!) + 1 : 0;
  };

  const customTags = (templateRef?: string) => {
    if (!templateRef) return [];
    const rel = htmlFiles.get(templateRef);
    if (!rel) return [];
    const html = readFileSync(join(stockDir, rel), "utf8");
    const tags = [...new Set([...html.matchAll(/<([a-z][a-z0-9]*-[a-z0-9-]+)/g)].map((m) => m[1]))];
    return tags.filter((t) => !t.startsWith("ui-view"));
  };
  const link = (rel: string, label = rel.split("/").pop()!) => `[${label}](stock/${rel})`;

  const lines: string[] = [];
  const out = (s = "") => lines.push(s);
  out("# Stock UI site map");
  out();
  out("Generated by `bun reference/dump.ts`. Every ui-router state of the stock UI, grouped by the page (CEF document)");
  out("that hosts it. URLs are hash routes (`/start/index.html#<url>`); the stock start page is reachable as");
  out("`/start/stock.html#<url>` while our bundle is installed. Template/component links point into `stock/` (gitignored, run the dump).");
  out();
  out("The game switches pages itself based on `GET /navigation/state` → `state.navigationState`; the stock JS only reads it");
  out("(`framework/services/NavigationService`). Abstract states are layouts (tabs/frames) for their children.");
  out();

  const apps = [...new Set(routes.map((r) => (r.name.startsWith("event-settings") ? "framework" : r.app)))];
  const order = ["start", "framework", "event", "loading", "tuning", "materialeditor"].filter((a) => apps.includes(a));
  let screens = 0;
  for (const app of order) {
    const list = routes
      .filter((r) => r.app === app)
      .sort((a, b) => fullUrl(a).localeCompare(fullUrl(b)) || a.name.localeCompare(b.name));
    const info = PAGES[app];
    out(`## ${app} — \`${info?.page ?? "?"}\``);
    out();
    if (info) out(info.when), out();
    // tree order: sort by state name so children follow parents
    const tree = [...list].sort((a, b) => a.name.localeCompare(b.name));
    for (const r of tree) {
      if (!r.abstract) screens++;
      const indent = "  ".repeat(depth(r));
      const title = r.title ? ` — **${r.title}**` : "";
      const url = fullUrl(r);
      const shots: string[] = [];
      if (existsSync(join(here, "screenshots", `${r.name}.png`))) shots.push(`[screenshot](screenshots/${r.name}.png)`);
      if (existsSync(join(here, "screenshots", "game", `${r.name}.png`))) shots.push(`[in game](screenshots/game/${r.name}.png)`);
      for (const f of tabShots.filter((f) => f.startsWith(`${r.name}~`))) shots.push(`[${f.split("~")[1].replace(/\.png$/, "")}](screenshots/${f})`);
      const status = shotIndex[r.name] && !shotIndex[r.name].ok ? ` · _not reachable directly${shotIndex[r.name].error ? " (needs params)" : ""}_` : "";
      out(`${indent}- \`${r.name}\`${title}${r.abstract ? " _(layout)_" : ""}${url ? ` · \`#${url}\`` : ""}${shots.length ? ` · ${shots.join(" · ")}` : ""}${status}`);
      const details: string[] = [];
      if (r.controller || r.component) details.push(`controller: \`${r.controller ?? r.component}\``);
      if (r.templateUrl) details.push(`template: ${htmlFiles.has(r.templateUrl) ? link(htmlFiles.get(r.templateUrl)!) : `\`${r.templateUrl}\``}`);
      if (r.params?.length) details.push(`params: ${r.params.map((p) => `\`${p}\``).join(", ")}`);
      if (details.length) out(`${indent}  ${details.join(" · ")}`);
      const tags = customTags(r.templateUrl);
      if (tags.length) out(`${indent}  components: ${tags.map((t) => (componentTemplates.has(t) ? link(componentTemplates.get(t)!, t) : `\`${t}\``)).join(", ")}`);
    }
    out();
  }
  out("## New UI (this repo)");
  out();
  out("Screenshots of `src/` routes: `bun reference/newui-screenshots.ts`.");
  out();
  for (const f of newUiShots) out(`- [${f.replace(/\.png$/, "")}](screenshots/new-ui/${f})`);
  out();
  lines.splice(8, 0, `${screens} screens (${routes.length} states including layouts). Screenshots: \`bun reference/screenshots.ts [--app event] [--window]\` (gitignored);`, "\"in game\" = real game-window capture (3D + UI composited), see [UI_SHELL.md](UI_SHELL.md).", "");

  write(join(here, "SITEMAP.md"), lines.join("\n"));
  console.log(`sitemap: ${screens} screens`);
}

if (import.meta.main) sitemap();
