// Extracts the stock UI's setup-setting labels and tabs (event/setup/*/…service.js) into
// src/session/garageLabels.ts, so the new garage shows the same names. Run: bun reference/garage-labels.ts
import { Glob } from 'bun'
import { join } from 'path'

const SETUP = join(import.meta.dir, 'stock/app.event/event/modules/event/setup')
const labels: Record<string, string> = {}
const tabs: Record<string, string> = {}
const captions: Record<string, string> = {}

for await (const file of new Glob('*/*.js').scan(SETUP)) {
  const src = await Bun.file(join(SETUP, file)).text()
  const names: Record<string, string> = {}
  for (const m of src.matchAll(/this\.(\w+)\s*=\s*this\.utilService\.i18n\.translate\("((?:[^"\\]|\\.)*)"\)/g)) {
    const fallback = m[2].match(/undefined\{([^}]*)\}/)
    names[m[1]] = fallback ? fallback[1] : m[2]
  }
  const tab = file.split(/[\\/]/)[0]
  // ICU selects keyed by the setting's caption: "{CAPTION, select, s_rear_wing{Rear wing} … other{ {CAPTION} } }"
  for (const m of src.matchAll(/\{CAPTION, select, ((?:[^"\\]|\\.)*)"/g)) {
    for (const opt of m[1].matchAll(/(\w+)\{([^{}]+)\}/g)) if (opt[1] !== 'other' && opt[1] !== 'undefined') captions[opt[1]] ??= opt[2].trim()
  }
  for (const m of src.matchAll(/\{\s*key:\s*"([^"]+)"([^}]*?)label:\s*(?:this\.utilService\.i18n\.translate\("((?:[^"\\]|\\.)*)"\)|this\.(\w+)|"([^"]*)")/g)) {
    const icu = m[3] ? (m[3].match(/undefined\{([^}]*)\}/)?.[1] ?? m[3].match(/select, \w+\{([^}]*)\}/)?.[1]) : undefined
    const label = icu ?? (m[4] ? names[m[4]] : m[5])
    if (!label) continue
    const keys = [m[1], ...Array.from((m[2].match(/addKeys:\s*\[([^\]]*)\]/)?.[1] ?? '').matchAll(/"([^"]+)"/g), (k) => k[1])]
    for (const k of keys) {
      labels[k] ??= label.trim()
      tabs[k] ??= tab
    }
  }
}

const out = join(import.meta.dir, '..', 'src', 'session', 'garageLabels.ts')
await Bun.write(
  out,
  `// Generated by reference/garage-labels.ts from the stock UI's setup services. Do not edit.\n` +
    `export const GARAGE_LABELS: Record<string, string> = ${JSON.stringify(labels, null, 2)}\n\n` +
    `/** labels by the setting's caption (mods name e.g. the rear wing "s_rear_downforce"); preferred over GARAGE_LABELS */
` +
    `export const GARAGE_CAPTIONS: Record<string, string> = ${JSON.stringify(captions, null, 2)}

` +
    `/** stock setup tab of each key: chassis, dampers, powertrain, strategy, suspension-aero, wheels-brakes */\n` +
    `export const GARAGE_TABS: Record<string, string> = ${JSON.stringify(tabs, null, 2)}\n`,
)
console.log(`${Object.keys(labels).length} labels -> ${out}`)
