// Generates src/settings/controlLabels.ts: the assignable controls in the stock UI's groups and order,
// read from the stock assign controllers (reference/stock/ui.framework/.../settings/assign).
//   bun reference/control-labels.ts
import { readdirSync, readFileSync, writeFileSync } from 'fs'
import { join } from 'path'

const DIR = join(import.meta.dir, 'stock', 'ui.framework', 'framework', 'modules', 'framework', 'settings', 'assign')
const OUT = join(import.meta.dir, '..', 'src', 'settings', 'controlLabels.ts')

// file → page title, in the stock page order
const PAGES: [string, string][] = [
  ['assign-driving', 'Driving'],
  ['assign-electronics', 'Electronics'],
  ['assign-assists', 'Assists & gameplay'],
  ['assign-camera', 'Cameras & seat'],
  ['assign-ui', 'UI & chat'],
  ['assign-cinematic-cameras', 'Cinematic cameras'],
]

// getDrivingCameraControls → "Driving camera"
const TITLES: Record<string, string> = { 'Seat and fov': 'Seat & field of view', Hud: 'HUD', Ui: 'Menus & UI', Alternative: 'Alternative inputs' }
const groupTitle = (method: string) => {
  const words = method.replace(/^get/, '').replace(/Controls$/, '').replace(/([a-z])([A-Z])/g, '$1 $2')
  const title = words.charAt(0) + words.slice(1).toLowerCase()
  return TITLES[title] ?? title
}

type Group = { id: string; page: string; title: string; items: { key: string; label: string }[] }
const groups: Group[] = []
const files = new Set(readdirSync(DIR))
for (const [file, page] of PAGES) {
  if (!files.has(`${file}.controller.js`)) throw new Error(`missing ${file}`)
  const src = readFileSync(join(DIR, `${file}.controller.js`), 'utf8')
  // each getter: get<Name>Controls() { return [ { key: "CC_…", name: i18n.translate("…") }, … ]; }
  for (const m of src.matchAll(/(get\w+Controls)\(\) \{\s*return \[([\s\S]*?)\];/g)) {
    const items = [...m[2].matchAll(/key: "(CC_\w+)", name: [\w.]*translate\("([^"]+)"\)/g)].map(([, key, label]) => ({ key, label }))
    if (items.length) groups.push({ id: m[1], page, title: groupTitle(m[1]), items })
  }
}

const body = `// Generated by reference/control-labels.ts from the stock assign pages. Do not edit.
export type ControlGroup = { id: string; page: string; title: string; items: { key: string; label: string }[] }

export const CONTROL_GROUPS: ControlGroup[] = ${JSON.stringify(groups, null, 2)}
`
writeFileSync(OUT, body)
console.log(`${groups.length} groups, ${groups.reduce((n, g) => n + g.items.length, 0)} controls → ${OUT}`)
